// Build-time template bundler.
//
// The generator engine (lib/core.js) personalises a raw design template by
// string replacement. Those templates live at <repo>/designs/*.html and the
// runtime wiring at <repo>/templates/wiring.js — both OUTSIDE this Next app.
//
// Reading them with fs at request time works locally but breaks on Vercel: a
// project whose Root Directory is apps/web does not ship sibling folders into
// the serverless function, and the repo root cannot be derived reliably from
// import.meta.url once the module is bundled.
//
// So we inline them into a plain JS module at build time. The result is part of
// the server bundle, always present, with no filesystem or path guessing.
//
// Usage: npm run gen:templates   (run automatically by pretest/prebuild/predev)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '..', '..', '..');
const designsDir = path.join(repoRoot, 'designs');
const wiringFile = path.join(repoRoot, 'templates', 'wiring.js');
const outFile = path.join(here, '..', 'lib', 'templates.generated.js');

const designIds = fs
  .readdirSync(designsDir)
  .filter((name) => name.endsWith('.html'))
  .map((name) => name.slice(0, -'.html'.length))
  .sort();

const designs = {};
for (const id of designIds) {
  designs[id] = fs.readFileSync(path.join(designsDir, `${id}.html`), 'utf8');
}
const wiring = fs.readFileSync(wiringFile, 'utf8');

const banner =
  '// AUTO-GENERATED by scripts/gen-templates.mjs — do not edit by hand.\n' +
  '// Source of truth: <repo>/designs/*.html and <repo>/templates/wiring.js.\n' +
  '// Regenerate with: npm run gen:templates\n';

const body =
  `export const WIRING = ${JSON.stringify(wiring)};\n\n` +
  `export const DESIGNS = ${JSON.stringify(designs, null, 2)};\n`;

fs.writeFileSync(outFile, banner + body, 'utf8');
console.log(`gen-templates: wrote ${designIds.length} designs -> ${path.relative(repoRoot, outFile)}`);
